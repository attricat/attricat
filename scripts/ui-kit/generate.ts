/**
 * Generates every artifact of the UI kit from `definition.ts`. It runs in
 * the web app's contract test: `UPDATE_CONTRACTS=1 pnpm --dir apps/web
 * vitest run uiKitContract` rewrites the files, and the test fails while any
 * is stale. Paths are relative to the repository root.
 */
import {
  hostIcons,
  type ElementDefinition,
  type PropSchema,
  uiKitElements,
  uiKitLimits,
  uiKitVersions,
} from './definition';

export const uiKitPaths = {
  contract: 'contracts/ui-kit-v1.schema.json',
  released: (version: string) => `contracts/ui-kit-released/ui-kit-${version}.json`,
  hostValidators: 'apps/web/src/features/extensions/native/generated/uiKit.ts',
  referenceEn: 'apps/docs/src/content/docs/extensions/ui-kit.md',
  referencePl: 'apps/docs/src/content/docs/pl/extensions/ui-kit.md',
} as const;

const latest = uiKitVersions[uiKitVersions.length - 1];
const order = (left: string, right: string) => {
  const parse = (version: string) => version.split('.').map(Number);
  const [a, b] = [parse(left), parse(right)];
  for (let index = 0; index < 3; index += 1)
    if (a[index] !== b[index]) return a[index] - b[index];
  return 0;
};

/** The kit as a version shipped it: only what existed by then. */
export const projectUiKit = (version: string) => {
  const included = (since: string | undefined, fallback: string) =>
    order(since ?? fallback, version) <= 0;
  const elements: Record<string, unknown> = {};
  for (const [name, element] of Object.entries(uiKitElements)) {
    if (!included(element.since, element.since)) continue;
    const pick = <T extends { since?: string }>(items: Record<string, T>) =>
      Object.fromEntries(
        Object.entries(items)
          .filter(([, item]) => included(item.since, element.since))
          .map(([key, item]) => [
            key,
            { ...item, since: item.since ?? element.since },
          ]),
      );
    elements[name] = {
      tag: element.tag,
      since: element.since,
      description: element.description,
      props: pick(element.props),
      events: pick(element.events),
      children: element.children,
      slots: element.slots,
      methods: element.methods,
      accessibility: element.accessibility,
    };
  }
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: 'https://attricat.org/contracts/ui-kit-v1.schema.json',
    title: 'Attricat UI kit',
    version,
    versions: uiKitVersions.filter((item) => order(item, version) <= 0),
    icons: hostIcons,
    limits: uiKitLimits,
    elements,
  };
};

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

const quote = (value: string) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** The zod source of one prop schema. */
const zod = (schema: PropSchema): string => {
  if (Array.isArray(schema.type)) {
    return schema.type[0] === 'number'
      ? 'z.number().nullable()'
      : `z.string().max(${(schema as { maxLength: number }).maxLength}).nullable()`;
  }
  switch (schema.type) {
    case 'string':
      if (schema.enum) return `z.enum([${schema.enum.map(quote).join(', ')}])`;
      return schema.format === 'link'
        ? `z.string().max(${schema.maxLength}).refine(isUiKitLink)`
        : `z.string().max(${schema.maxLength})`;
    case 'boolean':
      return 'z.boolean()';
    case 'number':
      return `z.number()${schema.minimum === undefined ? '' : `.min(${schema.minimum})`}${schema.maximum === undefined ? '' : `.max(${schema.maximum})`}`;
    case 'integer':
      return `z.number().int().min(${schema.minimum}).max(${schema.maximum})`;
    case 'array': {
      const item =
        schema.items.type === 'string'
          ? `z.string().max(${schema.items.maxLength})`
          : zodObject(schema.items.properties, schema.items.required);
      return `z.array(${item}).max(${schema.maxItems})`;
    }
    case 'object':
      return `z.record(z.string(), z.union([z.string().max(${schema.additionalProperties.maxLength}), z.number(), z.null()])).refine((value) => Object.keys(value).length <= ${schema.maxProperties})`;
  }
};

const zodObject = (
  properties: Record<string, PropSchema>,
  required: readonly string[],
) =>
  `z.object({ ${Object.entries(properties)
    .map(
      ([key, schema]) =>
        `${key}: ${zod(schema)}${required.includes(key) ? '' : '.optional()'}`,
    )
    .join(', ')} }).strict()`;

const hostValidators = () => {
  const lines = [
    '// Generated by scripts/ui-kit/generate.ts from scripts/ui-kit/definition.ts.',
    '// Do not edit; run `UPDATE_CONTRACTS=1 pnpm vitest run uiKitContract`.',
    "import { z } from 'zod';",
    '',
    '/** An `https:` URL or an in-app path; never another scheme or host-relative `//`. */',
    'export const isUiKitLink = (value: string) => {',
    "  if (value.startsWith('/')) return !value.startsWith('//') && !value.includes('\\\\');",
    '  try {',
    "    return new URL(value).protocol === 'https:';",
    '  } catch {',
    '    return false;',
    '  }',
    '};',
    '',
    `/** UI kit versions this host draws, oldest first. */`,
    `export const uiKitVersions = [${uiKitVersions.map(quote).join(', ')}] as const;`,
    '',
    `export const uiKitLimits = ${JSON.stringify(uiKitLimits)} as const;`,
    '',
    '/** Every element: its tag, props with validators and defaults, events, children, slots, methods and required accessible names. */',
    'export const uiKitElements = {',
  ];
  for (const [name, element] of Object.entries(uiKitElements) as [
    string,
    ElementDefinition,
  ][]) {
    lines.push(`  ${name}: {`);
    lines.push(`    tag: ${quote(element.tag)},`);
    lines.push(`    since: ${quote(element.since)},`);
    lines.push('    props: {');
    for (const [prop, definition] of Object.entries(element.props)) {
      lines.push(
        `      ${prop}: { since: ${quote(definition.since ?? element.since)}, required: ${Boolean(definition.required)}, default: ${JSON.stringify(definition.default ?? null)}, schema: ${zod(definition.schema)} },`,
      );
    }
    lines.push('    },');
    lines.push('    events: {');
    for (const [event, definition] of Object.entries(element.events))
      lines.push(
        `      ${event}: { since: ${quote(definition.since ?? element.since)}, payload: ${zodObject(definition.payload, Object.keys(definition.payload))} },`,
      );
    lines.push('    },');
    lines.push(`    children: ${JSON.stringify(element.children)},`);
    lines.push(
      `    slots: {${Object.entries(element.slots)
        .map(([slot, value]) => ` ${slot}: [${value.allowed.map(quote).join(', ')}]`)
        .join(',')} },`,
    );
    lines.push(`    methods: [${element.methods.map(quote).join(', ')}],`);
    lines.push(
      `    accessibility: [${element.accessibility.map(quote).join(', ')}],`,
    );
    lines.push('  },');
  }
  lines.push('} as const;', '');
  lines.push('export type UiKitElementName = keyof typeof uiKitElements;', '');
  lines.push(
    '/** Element names by their custom element tag. */',
    'export const uiKitElementsByTag: Record<string, UiKitElementName> = Object.fromEntries(',
    '  Object.entries(uiKitElements).map(([name, element]) => [element.tag, name]),',
    ') as Record<string, UiKitElementName>;',
    '',
  );
  return lines.join('\n');
};

const describeSchema = (schema: PropSchema): string => {
  if (Array.isArray(schema.type)) return `${schema.type[0]} \\| null`;
  switch (schema.type) {
    case 'string':
      return schema.enum
        ? schema.enum.map((value) => `\`${value}\``).join(' \\| ')
        : `string ≤ ${schema.maxLength}`;
    case 'integer':
      return `integer ${schema.minimum}–${schema.maximum}`;
    case 'array':
      return schema.items.type === 'string'
        ? `string[] ≤ ${schema.maxItems}`
        : `{ ${Object.keys(schema.items.properties).join(', ')} }[] ≤ ${schema.maxItems}`;
    case 'object':
      return 'object';
    default:
      return schema.type;
  }
};

const reference = (locale: 'en' | 'pl') => {
  const t =
    locale === 'en'
      ? {
          title: 'UI kit reference',
          description:
            'Every element native extension UI can compose, with its props, events and limits.',
          intro: `This reference is generated from the UI kit definition and lists UI kit ${latest}. Each element is a Preact component in \`@attricat/ui-kit\`; Attricat validates what your Worker renders and draws it with its own components. Anything not listed here is dropped.`,
          prop: 'Prop',
          type: 'Type',
          details: 'Description',
          events: 'Events',
          payload: 'Payload',
          children: 'Children',
          childKinds: {
            none: 'none',
            text: 'plain text',
            elements: 'UI kit elements',
          },
          slots: 'Slots',
          methods: 'Methods',
          required: 'required',
          defaultValue: 'default',
          accessibility: 'Required accessible name',
          since: 'Since',
          icons: 'Host icons',
        }
      : {
          title: 'Dokumentacja zestawu UI',
          description:
            'Wszystkie elementy, z których rozszerzenie składa natywny interfejs, z właściwościami, zdarzeniami i limitami.',
          intro: `Ta dokumentacja jest generowana z definicji zestawu UI i opisuje zestaw UI ${latest}. Każdy element to komponent Preact z \`@attricat/ui-kit\`; Attricat sprawdza, co renderuje Worker rozszerzenia, i rysuje to własnymi komponentami. Wszystko, czego tu nie ma, jest pomijane.`,
          prop: 'Właściwość',
          type: 'Typ',
          details: 'Opis',
          events: 'Zdarzenia',
          payload: 'Dane',
          children: 'Elementy podrzędne',
          childKinds: {
            none: 'brak',
            text: 'zwykły tekst',
            elements: 'elementy zestawu UI',
          },
          slots: 'Gniazda',
          methods: 'Metody',
          required: 'wymagana',
          defaultValue: 'domyślnie',
          accessibility: 'Wymagana nazwa dostępna',
          since: 'Od wersji',
          icons: 'Ikony hosta',
        };
  const lines = [
    '---',
    `title: ${t.title}`,
    `description: ${t.description}`,
    '---',
    '',
    `<!-- Generated by scripts/ui-kit/generate.ts; edit scripts/ui-kit/definition.ts instead. -->`,
    '',
    t.intro,
    '',
  ];
  for (const [name, element] of Object.entries(uiKitElements) as [
    string,
    ElementDefinition,
  ][]) {
    lines.push(`## ${name}`, '', element.description[locale], '');
    lines.push(`${t.since}: ${element.since}. ${t.children}: ${t.childKinds[element.children.kind]}.`);
    if (element.accessibility.length)
      lines.push(
        `${t.accessibility}: ${element.accessibility.map((prop) => `\`${prop}\``).join(', ')}.`,
      );
    if (element.methods.length)
      lines.push(
        `${t.methods}: ${element.methods.map((method) => `\`${method}()\``).join(', ')}.`,
      );
    lines.push('');
    const props = Object.entries(element.props);
    if (props.length) {
      lines.push(`| ${t.prop} | ${t.type} | ${t.details} |`, '| --- | --- | --- |');
      for (const [prop, definition] of props) {
        const notes = [
          definition.required ? t.required : undefined,
          definition.default !== undefined && definition.default !== null
            ? `${t.defaultValue} \`${JSON.stringify(definition.default)}\``
            : undefined,
        ].filter(Boolean);
        lines.push(
          `| \`${prop}\` | ${describeSchema(definition.schema)} | ${definition.description[locale]}${notes.length ? ` (${notes.join(', ')})` : ''} |`,
        );
      }
      lines.push('');
    }
    const events = Object.entries(element.events);
    if (events.length) {
      lines.push(`| ${t.events} | ${t.payload} | ${t.details} |`, '| --- | --- | --- |');
      for (const [event, definition] of events)
        lines.push(
          `| \`${event}\` | \`{ ${Object.entries(definition.payload)
            .map(([key, schema]) => `${key}: ${describeSchema(schema).replace(/\\\|/g, '|')}`)
            .join(', ')} }\` | ${definition.description[locale]} |`,
        );
      lines.push('');
    }
    const slots = Object.entries(element.slots);
    if (slots.length) {
      lines.push(`${t.slots}:`, '');
      for (const [slot, definition] of slots)
        lines.push(
          `- \`${slot}\` (${definition.allowed.join(', ')}): ${definition.description[locale]}`,
        );
      lines.push('');
    }
  }
  lines.push(`## ${t.icons}`, '', hostIcons.map((icon) => `\`${icon}\``).join(', '), '');
  return lines.join('\n');
};

/** Every generated file, by path from the repository root. */
export const uiKitFiles = (): Record<string, string> => ({
  [uiKitPaths.contract]: json(projectUiKit(latest)),
  [uiKitPaths.hostValidators]: hostValidators(),
  [uiKitPaths.referenceEn]: reference('en'),
  [uiKitPaths.referencePl]: reference('pl'),
});

/**
 * Released versions are frozen: each one's projection of the current
 * definition must equal its snapshot, which is written once and never
 * rewritten.
 */
export const releasedUiKitSnapshots = (): Record<string, string> =>
  Object.fromEntries(
    uiKitVersions.map((version) => [
      uiKitPaths.released(version),
      json(projectUiKit(version)),
    ]),
  );
