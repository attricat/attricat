use clap::Subcommand;
use serde_json::{Map, Value, json};
use uuid::Uuid;

use crate::cli::PageArgs;
use crate::commands::identity_provider::{IdentityProviderCommand, identity_provider_command};
use crate::error::CliError;
use crate::transport::{Api, segment, with_query};

pub(crate) const OPERATOR_TOKEN_VARIABLE: &str = "ATTRICAT_OPERATOR_TOKEN";

#[derive(Subcommand)]
pub(crate) enum OperatorCommand {
    /// Workspaces of this deployment.
    #[command(subcommand)]
    Workspace(OperatorWorkspaceCommand),
}

#[derive(Subcommand)]
pub(crate) enum OperatorWorkspaceCommand {
    /// Create a workspace and invite its owner. Repeat with the same values to
    /// finish a request that failed part way.
    Create {
        /// Workspace UUID, generated by the caller so a retry is safe.
        #[arg(long)]
        id: Uuid,
        #[arg(long)]
        name: String,
        /// Domain-like sign-in identifier. It cannot be changed afterwards.
        #[arg(long)]
        login_identifier: String,
        #[arg(long)]
        owner_email: String,
        #[arg(long)]
        owner_display_name: Option<String>,
    },
    Get {
        id: Uuid,
    },
    List {
        #[command(flatten)]
        page: PageArgs,
    },
    /// The workspace's single sign-on provider.
    IdentityProvider {
        id: Uuid,
        #[command(subcommand)]
        command: IdentityProviderCommand,
    },
    /// Replace the owner invitation of a workspace that has no owner yet.
    InviteOwner {
        id: Uuid,
        /// A different address; defaults to the workspace's current one.
        #[arg(long)]
        owner_email: Option<String>,
        #[arg(long)]
        owner_display_name: Option<String>,
    },
}

const WORKSPACES_PATH: &str = "/operator/workspaces";

fn workspace_path(id: Uuid) -> String {
    format!("{WORKSPACES_PATH}/{}", segment(id))
}

pub(crate) async fn operator_command(
    api: &Api,
    command: OperatorCommand,
) -> Result<String, CliError> {
    let OperatorCommand::Workspace(command) = command;
    match command {
        OperatorWorkspaceCommand::Create {
            id,
            name,
            login_identifier,
            owner_email,
            owner_display_name,
        } => {
            api.put_json(
                &workspace_path(id),
                json!({
                    "name": name,
                    "login_identifier": login_identifier,
                    "owner_email": owner_email,
                    "owner_display_name": owner_display_name,
                }),
            )
            .await
        }
        OperatorWorkspaceCommand::Get { id } => api.get(&workspace_path(id)).await,
        OperatorWorkspaceCommand::IdentityProvider { id, command } => {
            identity_provider_command(
                api,
                &format!("{}/identity-provider", workspace_path(id)),
                command,
            )
            .await
        }
        OperatorWorkspaceCommand::List { page } => {
            api.get(&with_query(WORKSPACES_PATH, page.query())).await
        }
        OperatorWorkspaceCommand::InviteOwner {
            id,
            owner_email,
            owner_display_name,
        } => {
            let mut body = Map::new();
            if let Some(email) = owner_email {
                body.insert("owner_email".to_owned(), Value::String(email));
            }
            if let Some(name) = owner_display_name {
                body.insert("owner_display_name".to_owned(), Value::String(name));
            }
            api.post_json(
                &format!("{}/owner-invitation", workspace_path(id)),
                Value::Object(body),
            )
            .await
        }
    }
}
